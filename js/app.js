  function stats() {
    let sov = 0;
    let terr = 0;
    let land = 0;
    let people = 0;
    const per = {};
    const byLevel = { 1: 0, 2: 0, 3: 0, 4: 0 };
    for (const [code, lv] of marks) {
      const f = byCode.get(code);
      if (!f) continue;
      byLevel[lv]++;
      if (!BEEN.has(lv)) continue; // a wish is not a visit
      land += f.k || 0;
      people += f.p || 0;
      if (isCountry(f)) {
        sov++;
        per[f.r] = (per[f.r] || 0) + 1;
      } else terr++;
    }
    return {
      sov,
      terr,
      per,
      byLevel,
      wish: byLevel[4],
      land,
      people,
      total: SOVEREIGN_TOTAL,
      pct: Math.round((sov / SOVEREIGN_TOTAL) * 100),
      landPct: (land / WORLD_LAND) * 100,
      popPct: (people / WORLD_POP) * 100,
    };
  }

  /* ---------------- number formatting ---------------- */
  const compact = (v) =>
    new Intl.NumberFormat(localeOf(), { notation: 'compact', maximumFractionDigits: 1 }).format(v);
  // one decimal below 10% so a single country still registers
  const withPct = (v) =>
    new Intl.NumberFormat(localeOf(), { style: 'percent', maximumFractionDigits: v < 10 ? 1 : 0 }).format(v / 100);

  const cityOrder = () => (window.CITIES ? CITIES.c.map((c) => c.i) : []);

  function shareUrl() {
    const sub = Share.encodeSub(unitOrder(), subMarks);
    const cities = Share.encodeCities(cityOrder(), cityMarks);
    return (
      `${location.origin}${location.pathname}#v2=${encodeShare()}` +
      `${sub ? `&p=${sub}` : ''}${cities ? `&c=${cities}` : ''}`
    );
  }

  function shareMessage() {
    const s = stats();
    return t('shareText').replace('{n}', s.sov).replace('{total}', s.total).replace('{pct}', withPct(s.pct));
  }

