  const fold = (s) =>
    s
      .toLocaleLowerCase('tr')
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '')
      .replace(/ı/g, 'i');

  function filterList(q) {
    if (cityLayer) return buildCityList();
    const needle = fold(q.trim());
    let onShown = 0;
    let offShown = 0;
    if (detail) {
      for (const unit of detail.units) {
        const row = els[unit.c] && els[unit.c].row;
        if (!row) continue;
        const hit = !needle || fold([unit.n, ...Object.values(unit.L || {})].join('\u0000')).includes(needle);
        row.hidden = !hit;
        if (hit) (subMarks.has(unit.c) ? onShown++ : offShown++);
      }
      updateHeads(onShown, offShown);
      showEmpty(!onShown && !offShown);
      return;
    }
    for (const f of FEATURES) {
      const row = els[f.c]?.row;
      if (!row) continue;
      // search every language we carry, so "Germany" finds it while the UI is Turkish
      const matchesText = !needle || f.c.toLowerCase() === needle || searchIndex(f).includes(needle);
      const hit = matchesText && (!activeRegion || f.r === activeRegion);
      row.hidden = !hit;
      if (hit) (marks.has(f.c) ? onShown++ : offShown++);
    }
    updateHeads(onShown, offShown);
    showEmpty(!onShown && !offShown);
  }

